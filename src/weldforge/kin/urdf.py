def cell_to_srdf(
    cell: WeldCell,
    robot: RobotModel,
    name: str = "weldforge_cell",
    group: str = "arm",
    base_link: str = "base_link",
    tip_link: str = "torch_tip",
) -> str:
    """SRDF to match :func:`cell_to_urdf`.

    Generated alongside the URDF for the same reason: the collision exclusions
    have to name the links the URDF actually declares, and a hand-maintained
    SRDF goes stale the moment a cell gains a clamp.

    What gets excluded, and what deliberately does not:

    * **adjacent links** -- consecutive links always touch at their joint, so
      their collision pair is meaningless and MoveIt would report a permanent
      collision;
    * **the table against the robot base** -- they are bolted to the same
      floor and their simplified boxes overlap, while the real parts do not;
    * **clamps against the table** -- the clamps stand on it.

    Not excluded: the torch against anything, and the arm against the clamps.
    Those are the collisions that matter, and excluding them to quieten MoveIt
    is how a torch ends up in a fixture.
    """
    link_names = [base_link] + [f"link_{i + 1}" for i in range(robot.n_joints)] + [tip_link]
    lines = [
        '<?xml version="1.0"?>',
        "<!--",
        f"  {cell.name}",
        "  GENERATED by weldforge.kin.urdf alongside the URDF. Regenerate",
        "  rather than edit, or the link names will drift.",
        "-->",
        f'<robot name="{name}">',
        "",
        f'  <group name="{group}">',
        f'    <chain base_link="{base_link}" tip_link="{tip_link}"/>',
        "  </group>",
        "",
        '  <group_state name="home" group="' + group + '">',
    ]
    home = robot.home_joints()
    for joint, value in zip(robot.joints, home, strict=True):
        index = robot.joints.index(joint) + 1
        lines.append(f'    <joint name="joint_{index}" value="{float(value):.6f}"/>')
    lines += [
        "  </group_state>",
        "",
        '  <end_effector name="torch" parent_link="' + link_names[-2] + '" group="' + group + '"/>',
        "",
        "  <!-- The cell is bolted to the floor. -->",
        '  <virtual_joint name="fixed_base" type="fixed" parent_frame="world" child_link="world"/>',
        "",
        "  <!-- Adjacent links always touch at their joint. -->",
    ]
    for first, second in zip(link_names, link_names[1:], strict=False):
        lines.append(f'  <disable_collisions link1="{first}" link2="{second}" reason="Adjacent"/>')

    lines += [
        "",
        "  <!-- Robot base and bench: simplified boxes overlap, the real parts do not. -->",
        f'  <disable_collisions link1="{base_link}" link2="table" reason="Never"/>',
        '  <disable_collisions link1="link_1" link2="table" reason="Never"/>',
        "",
        "  <!-- Clamps stand on the bench. -->",
    ]
    for clamp in cell.fixture.clamps:
        safe = clamp.id.replace(" ", "_")
        lines.append(
            f'  <disable_collisions link1="clamp_{safe}" link2="table" reason="Adjacent"/>'
        )
    lines += ["", "</robot>"]
    return "\n".join(lines) + "\n"
