def robot_to_urdf(
    robot: RobotModel,
    name: str | None = None,
    base_link: str = "base_link",
    link_prefix: str = "link_",
    joint_prefix: str = "joint_",
    tool_link: str = "torch_tip",
    with_collision: bool = True,
    link_radius_mm: float = 60.0,
) -> str:
    """URDF ``<robot>`` document for *robot*.

    Visual and collision geometry is cylinders along each link: the real CAD
    of a robot arm is rarely available to a planner, and a capsule-like
    cylinder is what :mod:`weldforge.collide` checks against anyway, so the
    two stay consistent.
    """
    model_name = name or robot.name.lower().replace(" ", "_").replace("-", "_")
    lines: list[str] = [
        '<?xml version="1.0"?>',
        "<!--",
        f"  {robot.name}",
        "  GENERATED by weldforge.kin.urdf from data/robots/. Do not edit by",
        "  hand: regenerate instead, or the URDF and the planner's kinematics",
        "  will drift apart.",
        "",
        "  Link inertias are placeholders (uniform boxes). Replace them with",
        "  manufacturer data before using this model for dynamics.",
        "-->",
        f'<robot name="{model_name}">',
        "",
        f'  <link name="{base_link}">',
        "    <inertial>",
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        _inertial(50.0, 0.3),
        "    </inertial>",
        "  </link>",
        "",
    ]

    parent = base_link
    for index, joint in enumerate(robot.joints):
        child = f"{link_prefix}{index + 1}"
        transform = joint.transform(0.0)
        origin_xyz = _xyz(tf.translation_of(transform))
        origin_rpy = _rpy(tf.rotation_of(transform))
        joint_type = "prismatic" if joint.kind == "prismatic" else "revolute"
        # Limits: URDF is metres for prismatic axes, radians for revolute.
        if joint.kind == "prismatic":
            lower, upper = mm_to_m(joint.limit_lo), mm_to_m(joint.limit_hi)
            velocity = mm_to_m(joint.max_velocity)
        else:
            lower, upper = joint.limit_lo, joint.limit_hi
            velocity = joint.max_velocity

        # Link length for the visual: the distance to the next frame.
        next_transform = (
            robot.joints[index + 1].transform(0.0) if index + 1 < len(robot.joints) else robot.tool
        )
        length_mm = float(np.linalg.norm(tf.translation_of(next_transform)))

        lines += [
            f'  <joint name="{joint_prefix}{index + 1}" type="{joint_type}">',
            f'    <parent link="{parent}"/>',
            f'    <child link="{child}"/>',
            f'    <origin xyz="{origin_xyz}" rpy="{origin_rpy}"/>',
            '    <axis xyz="0 0 1"/>',
            f'    <limit lower="{lower:.9f}" upper="{upper:.9f}" '
            f'effort="1000" velocity="{velocity:.6f}"/>',
            '    <dynamics damping="0.5" friction="0.1"/>',
            "  </joint>",
            "",
            f'  <link name="{child}">',
            "    <inertial>",
            '      <origin xyz="0 0 0" rpy="0 0 0"/>',
            _inertial(max(2.0, 40.0 - index * 5.0), max(0.05, mm_to_m(length_mm))),
            "    </inertial>",
        ]
        if length_mm > 1.0:
            radius = mm_to_m(max(20.0, link_radius_mm - index * 8.0))
            geometry = (
                f'      <geometry><cylinder radius="{radius:.4f}" '
                f'length="{mm_to_m(length_mm):.4f}"/></geometry>'
            )
            # The cylinder is laid along the link, between this frame and the
            # next, which is where the metal actually is.
            direction = tf.unit(tf.translation_of(next_transform))
            if direction is None:
                direction = np.array([0.0, 0.0, 1.0])
            rotation = tf.rotation_between(np.array([0.0, 0.0, 1.0]), direction)
            centre = tf.translation_of(next_transform) / 2.0
            placement = f'      <origin xyz="{_xyz(centre)}" rpy="{_rpy(rotation)}"/>'
            lines += ["    <visual>", placement, geometry, "    </visual>"]
            if with_collision:
                lines += ["    <collision>", placement, geometry, "    </collision>"]
        lines += ["  </link>", ""]
        parent = child

    # Tool frame: flange to wire tip.
    lines += [
        f'  <joint name="{joint_prefix}tool" type="fixed">',
        f'    <parent link="{parent}"/>',
        f'    <child link="{tool_link}"/>',
        f'    <origin xyz="{_xyz(tf.translation_of(robot.tool))}" '
        f'rpy="{_rpy(tf.rotation_of(robot.tool))}"/>',
        "  </joint>",
        "",
        f'  <link name="{tool_link}">',
        "    <inertial>",
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        _inertial(2.0, 0.05),
        "    </inertial>",
        "  </link>",
        "",
        "</robot>",
    ]
    return "\n".join(lines) + "\n"


def cell_to_urdf(
    cell: WeldCell,
    robot: RobotModel,
    name: str = "weldforge_cell",
) -> str:
    """URDF for the whole cell: world, bench, clamps and the mounted robot.

    The robot's own links are inlined rather than included, so the result is a
    single self-contained file that ``robot_state_publisher`` and MoveIt can
    both load without an include path.
    """
    robot_body = robot_to_urdf(robot, name=f"{name}_arm")
    # Strip the wrapper so the arm's links can be nested in this document.
    inner = robot_body.split("\n")
    start = next(i for i, line in enumerate(inner) if line.startswith("<robot"))
    arm_lines = inner[start + 1 : -2]

    base_pose = cell.robot_base
    table = cell.fixture
    table_thickness_m = 0.06

    lines: list[str] = [
        '<?xml version="1.0"?>',
        "<!--",
        f"  {cell.name}",
        "  GENERATED by weldforge.kin.urdf: bench, clamps and the mounted",
        "  robot. Regenerate rather than edit.",
        "-->",
        f'<robot name="{name}">',
        "",
        '  <link name="world"/>',
        "",
        '  <joint name="world_to_cell" type="fixed">',
        '    <parent link="world"/>',
        '    <child link="cell"/>',
        '    <origin xyz="0 0 0" rpy="0 0 0"/>',
        "  </joint>",
        '  <link name="cell"/>',
        "",
        "  <!-- Welding bench -->",
        '  <joint name="cell_to_table" type="fixed">',
        '    <parent link="cell"/>',
        '    <child link="table"/>',
        f'    <origin xyz="{mm_to_m(float(table.table_origin[0])):.4f} '
        f"{mm_to_m(float(table.table_origin[1])):.4f} "
        f'{mm_to_m(table.table_z_mm) - table_thickness_m / 2.0:.4f}" rpy="0 0 0"/>',
        "  </joint>",
        '  <link name="table">',
        "    <inertial>",
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        _inertial(400.0, 1.0),
        "    </inertial>",
        "    <visual>",
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        f'      <geometry><box size="{mm_to_m(table.table_size_mm[0]):.4f} '
        f'{mm_to_m(table.table_size_mm[1]):.4f} {table_thickness_m:.4f}"/></geometry>',
        "    </visual>",
        "    <collision>",
        '      <origin xyz="0 0 0" rpy="0 0 0"/>',
        f'      <geometry><box size="{mm_to_m(table.table_size_mm[0]):.4f} '
        f'{mm_to_m(table.table_size_mm[1]):.4f} {table_thickness_m:.4f}"/></geometry>',
        "    </collision>",
        "  </link>",
        "",
    ]

    for clamp in table.clamps:
        safe = clamp.id.replace(" ", "_")
        height_m = mm_to_m(clamp.height_mm)
        lines += [
            f"  <!-- clamp {(clamp.name or clamp.id).replace('--', '-')} -->",
            f'  <joint name="cell_to_clamp_{safe}" type="fixed">',
            '    <parent link="cell"/>',
            f'    <child link="clamp_{safe}"/>',
            f'    <origin xyz="{_xyz(clamp.position)}" rpy="0 0 0"/>',
            "  </joint>",
            f'  <link name="clamp_{safe}">',
            "    <inertial>",
            '      <origin xyz="0 0 0" rpy="0 0 0"/>',
            _inertial(5.0, height_m),
            "    </inertial>",
            "    <visual>",
            f'      <origin xyz="0 0 {height_m / 2.0:.4f}" rpy="0 0 0"/>',
            f'      <geometry><cylinder radius="{mm_to_m(clamp.clearance_mm):.4f}" '
            f'length="{height_m:.4f}"/></geometry>',
            "    </visual>",
            "    <collision>",
            f'      <origin xyz="0 0 {height_m / 2.0:.4f}" rpy="0 0 0"/>',
            f'      <geometry><cylinder radius="{mm_to_m(clamp.clearance_mm):.4f}" '
            f'length="{height_m:.4f}"/></geometry>',
            "    </collision>",
            "  </link>",
            "",
        ]

    lines += [
        "  <!-- Robot, mounted where the cell says -->",
        '  <joint name="cell_to_robot" type="fixed">',
        '    <parent link="cell"/>',
        '    <child link="base_link"/>',
        f'    <origin xyz="{_xyz(tf.translation_of(base_pose))}" '
        f'rpy="{_rpy(tf.rotation_of(base_pose))}"/>',
        "  </joint>",
        "",
    ]
    lines.extend(arm_lines)
    lines += ["</robot>"]
    return "\n".join(lines) + "\n"


def write_urdf(text: str, path: str | Path) -> Path:
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    logger.info("wrote %s", out)
    return out


