"""URDF export and import.

One source of truth
-------------------
The robot geometry lives in ``data/robots/*.yaml`` as modified DH parameters,
because that is how the manufacturers publish it. ROS needs URDF. Keeping both
by hand guarantees they drift, and a drifted URDF means MoveIt plans for a
robot that is not the one the planner solved for -- so the URDF is **generated**
from the same data, and :func:`urdf_to_robot` reads it back so the round trip
can be tested.

The conversion is exact, not approximate. In modified DH the transform from
frame *i-1* to frame *i* at joint value zero is

.. code-block:: text

    T = Rx(alpha) * Tx(a) * Rz(theta_offset) * Tz(d)

and the joint rotates about the child frame's **Z**. URDF expresses exactly
that: ``<origin>`` carries ``T`` and ``<axis>`` is ``0 0 1``. So each DH row
becomes one URDF joint with no reparameterisation and no loss.

Units: URDF is metres and radians, the DH data is millimetres and radians, and
the conversion happens here.
"""

from __future__ import annotations

import logging
from pathlib import Path
from xml.etree import ElementTree

import numpy as np

from ..geom import transform as tf
from ..model import WeldCell
from ..units import m_to_mm, mm_to_m
from .robot import JointSpec, RobotModel

logger = logging.getLogger(__name__)

__all__ = [
    "robot_to_urdf",
    "cell_to_urdf",
    "cell_to_srdf",
    "urdf_to_robot",
    "write_urdf",
]


def _xyz(values: np.ndarray) -> str:
    return " ".join(f"{mm_to_m(float(v)):.9f}" for v in values)


def _rpy(rotation: np.ndarray) -> str:
    roll, pitch, yaw = tf.matrix_to_rpy(rotation)
    return f"{roll:.9f} {pitch:.9f} {yaw:.9f}"


def _inertial(mass_kg: float, size_m: float) -> str:
    """A plausible inertial block.

    Values are a solid box of the given mass and size. They are **not** the
    real link inertias, and are marked as such in the file: they are enough
    for Gazebo not to reject the model and for kinematic simulation, and quite
    insufficient for dynamics or torque estimation. A real cell must take them
    from the manufacturer's data.
    """
    inertia = mass_kg * (2.0 * size_m * size_m) / 12.0
    return (
        f'      <mass value="{mass_kg:.4f}"/>\n'
        f'      <inertia ixx="{inertia:.6f}" ixy="0" ixz="0" '
        f'iyy="{inertia:.6f}" iyz="0" izz="{inertia:.6f}"/>'
    )


