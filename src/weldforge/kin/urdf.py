def urdf_to_robot(
    source: str | Path,
    base_link: str = "base_link",
    tool_link: str | None = None,
) -> RobotModel:
    """Read a URDF back into a :class:`RobotModel`.

    Follows the chain from *base_link* through its movable joints. Each URDF
    joint becomes a DH row whose transform is the joint's ``<origin>``, which
    is the inverse of the export above -- so the round trip is lossless and
    testable.

    A URDF joint axis that is not ``0 0 1`` is rotated onto Z and the rotation
    folded into the origin, which is always possible for a single-axis joint.
    """
    # Distinguish a path from XML text by looking at the content, not by
    # trying the filesystem: ``Path(xml_text).exists()`` raises
    # "File name too long" on any real URDF.
    if isinstance(source, Path):
        text = source.read_text()
    else:
        candidate = str(source)
        text = candidate if candidate.lstrip().startswith("<") else Path(candidate).read_text()
    root = ElementTree.fromstring(text)

    joints_by_parent: dict[str, list[ElementTree.Element]] = {}
    for joint in root.findall("joint"):
        parent = joint.find("parent")
        if parent is None:
            continue
        joints_by_parent.setdefault(parent.get("link", ""), []).append(joint)

    specs: list[JointSpec] = []
    tool = tf.identity()
    current = base_link
    pending = tf.identity()

    while True:
        candidates = joints_by_parent.get(current, [])
        if not candidates:
            break
        joint = candidates[0]
        joint_type = joint.get("type", "fixed")
        origin = joint.find("origin")
        xyz = (
            np.array(
                [
                    float(v)
                    for v in (
                        origin.get("xyz", "0 0 0").split() if origin is not None else [0, 0, 0]
                    )
                ]
            )
            * 1000.0
        )
        rpy = np.array(
            [
                float(v)
                for v in (origin.get("rpy", "0 0 0").split() if origin is not None else [0, 0, 0])
            ]
        )
        transform = tf.pose(tf.rpy_to_matrix(*rpy), xyz)

        if joint_type == "fixed":
            pending = pending @ transform
            child = joint.find("child")
            current = child.get("link", "") if child is not None else ""
            if tool_link is not None and current == tool_link:
                tool = pending
                break
            continue

        axis_element = joint.find("axis")
        axis = np.array(
            [
                float(v)
                for v in (
                    axis_element.get("xyz", "0 0 1").split()
                    if axis_element is not None
                    else [0, 0, 1]
                )
            ]
        )
        align = tf.rotation_between(axis, np.array([0.0, 0.0, 1.0]))
        combined = pending @ transform @ tf.pose(align)
        pending = tf.identity()

        rotation = tf.rotation_of(combined)
        translation = tf.translation_of(combined)
        roll, pitch, yaw = tf.matrix_to_rpy(rotation)

        limit = joint.find("limit")
        lower = float(limit.get("lower", -np.pi)) if limit is not None else -np.pi
        upper = float(limit.get("upper", np.pi)) if limit is not None else np.pi
        velocity = float(limit.get("velocity", 3.0)) if limit is not None else 3.0
        if joint_type == "prismatic":
            lower, upper, velocity = m_to_mm(lower), m_to_mm(upper), m_to_mm(velocity)

        # Recover the DH row: alpha and a from the X-axis part, theta_offset
        # and d from the Z part. Exact for a chain produced by the exporter.
        specs.append(
            JointSpec(
                name=joint.get("name", f"J{len(specs) + 1}"),
                alpha=roll,
                a=float(translation[0]),
                d=float(translation[2] / np.cos(roll))
                if abs(np.cos(roll)) > 1e-9
                else float(-translation[1] / np.sin(roll)),
                theta_offset=yaw,
                kind="prismatic" if joint_type == "prismatic" else "revolute",
                limit_lo=lower,
                limit_hi=upper,
                max_velocity=velocity,
            )
        )
        del pitch  # a DH row has no pitch term; it is zero for exported chains

        child = joint.find("child")
        current = child.get("link", "") if child is not None else ""
        if not current:
            break

    return RobotModel(
        name=root.get("name", "urdf_robot"),
        joints=specs,
        tool=tool,
        reach_mm=0.0,
    )


