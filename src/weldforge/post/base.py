"""Postprocessor interface and shared helpers.

A postprocessor turns a :class:`~weldforge.model.WeldJob` into something a
particular controller will run. They are kept apart from the planner because
the differences are not cosmetic:

* **units** -- ABB, KUKA and Fanuc work in millimetres; Universal Robots works
  in metres; ROS 2 works in metres;
* **orientation** -- RAPID carries quaternions, KRL carries Z-Y-X Euler angles
  in degrees, Fanuc carries W-P-R, URScript carries a rotation vector;
* **arc control** -- RAPID has first-class ``ArcLStart``/``ArcL``/``ArcLEnd``
  with weld data; the others set digital outputs and wait for the power source
  to answer.

Each target declares its own units at the top of its module and converts at
the boundary, so nothing inside the core ever has to know.

Every generator emits a header recording the job, the seams, the procedure and
a warning that the program is machine-generated and must be dry-run before it
is let near a part. That header is not decoration: it is what lets whoever
finds the file on a controller in two years' time know where it came from.
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime, timezone

import numpy as np

from ..geom import transform as tf
from ..model import PathPoint, TorchPath, WeldJob, WeldPass, WeldProcedure

logger = logging.getLogger(__name__)

__all__ = ["PostOptions", "PostResult", "Postprocessor", "header_lines", "job_statistics"]


@dataclass
class PostOptions:
    """Common output options."""

    program_name: str = "WELDJOB"
    include_comments: bool = True
    include_header: bool = True
    # Skip stations whose joints were never solved. On by default: emitting a
    # move the robot cannot reach puts the fault on the shop floor instead of
    # in the planner's report.
    skip_unreachable: bool = True
    # Emit the whole job as one program, or one program per seam.
    split_per_seam: bool = False
    tool_name: str = "tWeldTorch"
    workobject_name: str = "wobjTable"
    # Decimal places for positions and angles.
    position_precision: int = 3
    angle_precision: int = 4
    author: str = "WeldForge"


@dataclass
class PostResult:
    """Generated program text, plus whatever the generator had to say."""

    files: dict[str, str] = field(default_factory=dict)
    warnings: list[str] = field(default_factory=list)
    target: str = ""
    n_moves: int = 0
    n_skipped: int = 0

    @property
    def main(self) -> str:
        """The single program, or the first file when split per seam."""
        return next(iter(self.files.values()), "")

    def summary(self) -> dict:
        return {
            "target": self.target,
            "files": list(self.files),
            "moves": self.n_moves,
            "skipped": self.n_skipped,
            "warnings": list(self.warnings),
        }


def job_statistics(job: WeldJob) -> dict[str, float | int | str]:
    """Figures worth putting in a program header."""
    return {
        "part": job.part.name if job.part else "",
        "cell": job.cell.name if job.cell else "",
        "seams": len(job.selected_seams),
        "weld_length_mm": round(job.total_weld_length_mm, 1),
        "passes": sum(p.n_passes for p in job.procedures.values()),
        "cycle_time_s": round(job.report.cycle_time_s, 1),
        "wire_kg": round(job.report.wire_consumption_kg, 3),
        "gas_l": round(job.report.gas_consumption_l, 1),
    }


def header_lines(job: WeldJob, options: PostOptions, comment: str = "!") -> list[str]:
    """Provenance header, in the target's comment syntax."""
    stats = job_statistics(job)
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        f"{comment} ============================================================",
        f"{comment} {options.program_name} - generated by {options.author}",
        f"{comment} {now}",
        f"{comment} ------------------------------------------------------------",
        f"{comment} part            : {stats['part']}",
        f"{comment} cell            : {stats['cell']}",
        f"{comment} seams           : {stats['seams']}",
        f"{comment} passes          : {stats['passes']}",
        f"{comment} weld length     : {stats['weld_length_mm']} mm",
        f"{comment} est. cycle time : {stats['cycle_time_s']} s",
        f"{comment} wire / gas      : {stats['wire_kg']} kg / {stats['gas_l']} l",
        f"{comment} ------------------------------------------------------------",
        f"{comment} MACHINE GENERATED. Dry-run at reduced speed with the arc",
        f"{comment} disabled before welding a part. Verify the tool frame, the",
        f"{comment} work object and every axis sign against this cell.",
    ]
    if not job.report.ok:
        lines.append(f"{comment} ")
        lines.append(f"{comment} *** THE PLANNER REPORTED PROBLEMS WITH THIS JOB ***")
        for error in job.report.errors[:10]:
            lines.append(f"{comment}   - {error}")
    lines.append(f"{comment} ============================================================")
    return lines


class Postprocessor(ABC):
    """Base class for a controller-specific generator."""

    #: Short identifier used by the registry and the CLI.
    key: str = ""
    #: Human-readable target name.
    target: str = ""
    #: ``'mm'`` or ``'m'`` -- the units the controller expects.
    units: str = "mm"
    #: File extension for generated programs.
    extension: str = "txt"
    #: Comment prefix.
    comment: str = "!"

    def __init__(self, options: PostOptions | None = None) -> None:
        self.options = options or PostOptions()

    # -- helpers -------------------------------------------------------------

    def scale(self, value: np.ndarray | float) -> np.ndarray | float:
        """Convert a length from millimetres to the target's units."""
        if self.units == "m":
            return (
                np.asarray(value, dtype=float) / 1000.0
                if isinstance(value, np.ndarray)
                else value / 1000.0
            )
        return value

    def position(self, point: PathPoint) -> np.ndarray:
        return np.asarray(self.scale(tf.translation_of(point.pose)), dtype=float)

    def speed(self, point: PathPoint) -> float:
        """Programmed speed in the target's units per second."""
        return float(self.scale(point.speed_mm_s))

    def usable_points(self, path: TorchPath) -> tuple[list[PathPoint], int]:
        """``(points, skipped)`` after dropping unreachable stations if asked."""
        if not self.options.skip_unreachable:
            return list(path.points), 0
        usable = [p for p in path.points if p.joints is not None or "unreachable" not in p.comment]
        return usable, len(path.points) - len(usable)

    def pass_for(self, job: WeldJob, path: TorchPath) -> WeldPass | None:
        procedure: WeldProcedure | None = job.procedures.get(path.seam_id)
        if procedure is None or path.pass_index >= len(procedure.passes):
            return None
        return procedure.passes[path.pass_index]

    def seam_comment(self, job: WeldJob, path: TorchPath) -> str:
        seam = job.seam(path.seam_id)
        weld_pass = self.pass_for(job, path)
        bits = [path.seam_id]
        if seam is not None:
            bits.append(f"{seam.joint_type.value} {seam.length_mm:.0f} mm")
            bits.append(seam.dominant_position.value)
        if weld_pass is not None:
            bits.append(
                f"pass {weld_pass.index + 1} '{weld_pass.name}' "
                f"{weld_pass.current_a:.0f}A {weld_pass.voltage_v:.1f}V "
                f"{weld_pass.travel_speed_mm_s:.1f}mm/s"
            )
        return " | ".join(bits)

    # -- interface -----------------------------------------------------------

    @abstractmethod
    def generate(self, job: WeldJob) -> PostResult:
        """Produce the program files for *job*."""

    def __repr__(self) -> str:  # pragma: no cover
        return f"<{type(self).__name__} target={self.target!r} units={self.units!r}>"
